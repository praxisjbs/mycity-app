"use strict";
/**
 * /api/v1/recruitment/contracts: the hire's employment contract on Recruitment · Onboarding
 * (docs/guides/offers.md §5).
 *
 *   GET  /:id, /:id/document            `recruitment` view: scope by the vacancy's hiring manager
 *   POST /:id/sign                      `recruitment` view: the signer named on its own request signs
 *                                       for the company (signatures.signAsStaffIn checks them)
 *   POST /:id/resend                    `recruitment` edit: a fresh link to the hire
 *   GET, PUT /settings/template, POST /settings/template/restore   `recruitment` edit: the wording
 *
 * A contract is generated by the offer's acceptance, never by a route here, and the hire signs it
 * on the public signing page (signatures.public.routes.js).
 */
const express = require("express");
const c = require("@mycity/contract");
const { route } = require("../../http/route");
const { requirePermission } = require("../../middleware/rbac");
const controller = require("./employment_contracts.controller");

const router = express.Router();
const ec = c.employment_contracts;
const byId = { params: c.common.IdParams };
const view = requirePermission("recruitment", "view");
const edit = requirePermission("recruitment", "edit");

route(router, "get", "/settings/template", { response: ec.ContractTemplate, summary: "The standard contract wording" }, edit, controller.template);
route(router, "put", "/settings/template", { body: ec.ContractTemplateSave, response: ec.ContractTemplate, summary: "Save the standard contract wording" }, edit, controller.saveTemplate);
route(router, "post", "/settings/template/restore", { body: c.common.EmptyBody, response: ec.ContractTemplate, summary: "Restore the shipped wording" }, edit, controller.restoreTemplate);
route(router, "get", "/:id", { ...byId, response: ec.EmploymentContractView, summary: "One employment contract" }, view, controller.get);
route(router, "post", "/:id/sign", { ...byId, body: c.signatures.SignSubmit, response: ec.EmploymentContractView, summary: "Sign the contract for the company" }, view, controller.sign);
route(router, "post", "/:id/resend", { ...byId, body: c.common.EmptyBody, response: ec.EmploymentContractView, summary: "Send the hire's signing link again" }, edit, controller.resend);
route(router, "get", "/:id/document", { ...byId, no_content: true, summary: "The contract's PDF" }, view, controller.document);

module.exports = { basePath: "/recruitment/contracts", surface: "staff", router };
