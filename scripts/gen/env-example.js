#!/usr/bin/env node
"use strict";
/**
 * Write .env.example from src/config/env.js, so the example can never list a
 * variable the app does not read, or miss one it does.
 *
 *   npm run gen:env              write .env.example
 *   node scripts/gen/env-example.js --check    exit 1 when .env.example is stale (CI)
 *
 * Values are the local defaults, so a copied .env.example runs on a laptop as is.
 * Where a server needs something different, the comment says what. Secrets are
 * written empty; nothing real is ever printed.
 */
const fs = require("node:fs");
const path = require("node:path");

process.env.MYCITY_SKIP_DOTENV = "1";
const { ENTRIES } = require("../../src/config/env");

const ROOT = path.resolve(__dirname, "..", "..");
const FILE = path.join(ROOT, ".env.example");

function defaultOf(schema) {
  const r = schema.safeParse(undefined);
  if (!r.success || r.data === undefined || r.data === null) return "";
  return String(r.data);
}

function render() {
  const out = [
    "# MyCity App: environment variables.",
    "# GENERATED by scripts/gen/env-example.js from src/config/env.js. Do not edit; run `npm run gen:env`.",
    "#",
    "# Local: copy to .env and fill what you need; empty secrets use development values.",
    "# Servers: /srv/mycity/<prod|stg>/shared/.env, mode 600. Every secret is required there,",
    "# and the API refuses to start without it.",
  ];
  let group = null;
  for (const [key, schema, meta] of ENTRIES) {
    if (meta.group !== group) {
      group = meta.group;
      out.push(
        "",
        `# ---- ${group} ${"-".repeat(Math.max(0, 60 - group.length))}`,
      );
    }
    const value = meta.secret ? "" : defaultOf(schema);
    const server =
      !meta.secret && meta.example !== undefined && meta.example !== value
        ? ` On servers: ${meta.example}`
        : "";
    out.push(`# ${meta.doc}${server}${meta.secret ? " SECRET." : ""}`);
    out.push(`${key}=${value}`);
  }
  return `${out.join("\n")}\n`;
}

const next = render();
if (process.argv.includes("--check")) {
  const current = fs.existsSync(FILE) ? fs.readFileSync(FILE, "utf8") : "";
  if (current !== next) {
    console.error(
      ".env.example is out of date with src/config/env.js. Run: npm run gen:env",
    );
    process.exit(1);
  }
  console.log(".env.example: up to date");
} else {
  fs.writeFileSync(FILE, next);
  console.log(`wrote .env.example (${ENTRIES.length} variables)`);
}
